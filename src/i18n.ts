let lang: 'uz' | 'en' = 'uz';
try {
  if (localStorage.getItem('office.lang') === 'en') lang = 'en';
} catch {
  /* storage unavailable */
}

export const t = (): Strings => (lang === 'uz' ? uz : en);
export const currentLang = () => lang;
export function toggleLang() {
  lang = lang === 'uz' ? 'en' : 'uz';
  try {
    localStorage.setItem('office.lang', lang);
  } catch {
    /* storage unavailable */
  }
}
